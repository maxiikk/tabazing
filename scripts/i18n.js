// Writes, from dictionaries/<lang>.json (`npm run i18n`):
//   _locales/<lang>/messages.json  what Chrome itself reads, for what manifest.json names with __MSG_key__ (the
//                                  extension's name, description, shortcut names, toolbar title);
//   utils/background-messages.js   the texts the service worker shows (the translate('…') calls in background.js),
//                                  in every language, as a JavaScript module: Chrome can't start a service worker
//                                  again (after it was idle) when it imports JSON, so it can't read the dictionaries.
// dictionaries/ holds every string Tabazing shows, one file per language. Run this after changing any of those
// keys, or after adding a language; tests/utils/dictionaries.test.js fails until you do.
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (path) => readFileSync(join(ROOT, path), 'utf8');

/** The languages there are dictionaries for: ['ar', 'de', 'el', 'en', …]. */
export const languages = () => readdirSync(join(ROOT, 'dictionaries')).filter((filename) => filename.endsWith('.json')).map((filename) => filename.slice(0, -5)).sort();
/** The keys manifest.json asks Chrome for (__MSG_key__). */
export const manifestKeys = () => [...new Set([...read('manifest.json').matchAll(/__MSG_(\w+)__/g)].map((match) => match[1]))].sort();

/** The messages.json text for one language: just the manifest's keys, in Chrome's { key: { message } } form. */
export function localeFile(lang) {
  const dict = JSON.parse(read(`dictionaries/${lang}.json`));
  const out = {};
  for (const key of manifestKeys()) {
    if (typeof dict[key] !== 'string') throw new Error(`dictionaries/${lang}.json has no "${key}" (manifest.json uses __MSG_${key}__)`);
    out[key] = { message: dict[key] };
  }
  return JSON.stringify(out, null, 3) + '\n';
}

/** The keys background.js translates: the literal first argument of each translate('…') call. */
export const backgroundKeys = () => [...new Set([...read('background.js').matchAll(/\btranslate\('(\w+)'/g)].map((match) => match[1]))].sort();

/** The text of utils/background-messages.js: { lang: { key: message } } for backgroundKeys(), every language. */
export function backgroundMessagesFile() {
  const books = {};
  for (const lang of languages()) {
    const dict = JSON.parse(read(`dictionaries/${lang}.json`));
    books[lang] = Object.fromEntries(backgroundKeys().map((key) => {
      if (typeof dict[key] !== 'string') throw new Error(`dictionaries/${lang}.json has no "${key}" (background.js translates it)`);
      return [key, dict[key]];
    }));
  }
  return `// Generated by \`npm run i18n\` (scripts/i18n.js) from dictionaries/: never edit it by hand.
// The texts the service worker shows (the translate('…') calls in background.js), in every language. The worker can't
// read the dictionaries themselves: Chrome can't start a service worker again (after it was idle) when it imports JSON.
export default ${JSON.stringify(books, null, 2)};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  for (const lang of languages()) {
    mkdirSync(join(ROOT, '_locales', lang), { recursive: true });
    writeFileSync(join(ROOT, '_locales', lang, 'messages.json'), localeFile(lang));
    console.log(`_locales/${lang}/messages.json`);
  }
  writeFileSync(join(ROOT, 'utils', 'background-messages.js'), backgroundMessagesFile());
  console.log('utils/background-messages.js');
}
